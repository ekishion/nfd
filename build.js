// ==============================================================================
// build.js - Lightweight Bundler with Conditional Tree-Shaking for NFD
// Bundles src/*.js and src/notifiers/*.js into a single worker.js module
// ==============================================================================

const fs = require('fs');
const path = require('path');

const SRC_DIR = path.join(__dirname, 'src');
const DATA_DIR = path.join(__dirname, 'data');
const OUTPUT_FILE = path.join(__dirname, 'worker.js');

const NOTIFIER_MAP = [
  { key: 'pushdeer', file: 'notifiers/pushdeer.js', env: 'ENV_PUSHDEER_KEY' },
  { key: 'serverchan', file: 'notifiers/serverchan.js', env: 'ENV_SERVERCHAN_KEY' },
];

function resolveActiveModules() {
  const isBuildAll = process.env.BUILD_ALL_NOTIFIERS === 'true' || process.env.NODE_ENV === 'test';

  // Find which notifier channels have environment variables configured
  const activeChannels = NOTIFIER_MAP.filter((item) => {
    if (isBuildAll) return true;
    const val = process.env[item.env];
    return val && String(val).trim().length > 0;
  });

  const baseModules = [
    'config.js',
    'cache.js',
    'telegram.js',
  ];

  const notifierModules = [];
  if (activeChannels.length > 0) {
    notifierModules.push('notifiers/base.js');
    for (const ch of activeChannels) {
      notifierModules.push(ch.file);
    }
    notifierModules.push('notifiers/index.js');
  } else {
    // Zero external notification channels configured: inject stub dispatcher without bundling any sub-channel files
    notifierModules.push({
      virtualName: 'notifiers/index.js (stub)',
      code: `
// Notification channels disabled / zero-bloat tree-shaken stub
export const notificationProviders = {};
export async function dispatchNotification() {}
`,
    });
  }

  const trailingModules = [
    'moderation.js',
    'pipeline.js',
    'panel.js',
    'admin.js',
    'index.js',
  ];

  return [...baseModules, ...notifierModules, ...trailingModules];
}

function bundle() {
  console.log('Bundling src/*.js into worker.js...');

  const header = [
    '// ==============================================================================',
    '// NFD (No Fraud / Node Forward Bot) - Cloudflare Worker',
    '// NOTE: This file is automatically generated by `node build.js` from `src/`.',
    '// To edit the codebase, modify files in `src/` and run `node build.js`.',
    '// ==============================================================================',
    '',
  ].join('\n');

  let defaultStartMsg = '';
  let defaultNotifyMsg = '';
  try {
    defaultStartMsg = fs.readFileSync(path.join(DATA_DIR, 'startMessage.md'), 'utf8').trim();
  } catch {}
  try {
    defaultNotifyMsg = fs.readFileSync(path.join(DATA_DIR, 'notification.txt'), 'utf8').trim();
  } catch {}

  const contents = [];
  const modules = resolveActiveModules();

  for (const mod of modules) {
    let file = '';
    let code = '';

    if (typeof mod === 'object' && mod.virtualName) {
      file = mod.virtualName;
      code = mod.code;
    } else {
      file = mod;
      const filePath = path.join(SRC_DIR, file);
      if (!fs.existsSync(filePath)) {
        console.error(`Missing module file: ${file}`);
        process.exit(1);
      }
      code = fs.readFileSync(filePath, 'utf8');
    }

    // In config.js, inline the data file contents
    if (file === 'config.js') {
      code = code.replace(/import\s+defaultStartMessage\s+from\s+['"].*?['"];?/g, `const defaultStartMessage = ${JSON.stringify(defaultStartMsg)};`);
      code = code.replace(/import\s+defaultNotification\s+from\s+['"].*?['"];?/g, `const defaultNotification = ${JSON.stringify(defaultNotifyMsg)};`);
    }

    // Strip all ES module imports (both single-line and multi-line)
    code = code.replace(/import\s+[\s\S]*?from\s+['"].*?['"];?\r?\n?/g, '');
    code = code.replace(/import\s+['"].*?['"];?\r?\n?/g, '');

    // Strip named exports: "export const", "export function", "export async function", "export let", "export var"
    code = code.replace(/^\s*export\s+(const|let|var|function|async function|class)\s+/gm, '$1 ');
    code = code.replace(/^\s*export\s*\{[^}]*\};?\r?\n?/gm, '');

    // Keep "export default" only in index.js, remove from any other file if present
    if (file !== 'index.js') {
      code = code.replace(/export\s+default\s*[\s\S]*?;\r?\n?/g, '');
    }

    contents.push(`// --- MODULE: ${file} ---\n` + code.trim());
  }

  const bundledCode = header + contents.join('\n\n') + '\n';
  fs.writeFileSync(OUTPUT_FILE, bundledCode, 'utf8');

  console.log(`Successfully generated ${OUTPUT_FILE} (${bundledCode.length} bytes)`);
}

bundle();
